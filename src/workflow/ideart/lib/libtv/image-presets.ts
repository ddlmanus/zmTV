export type LibTvImagePresetId = LibTvImagePresetDefinition["id"]

const LIBTV_IMAGE_PRESET_MAP = new Map<string, LibTvImagePresetDefinition>(
  LIBTV_IMAGE_SLASH_PRESETS.map((item) => [item.id, item])
)

export function getLibTvImagePresetById(presetId: string | null | undefined): LibTvImagePresetDefinition | null {
  const normalized = String(presetId || "").trim()
  if (!normalized) return null
  return LIBTV_IMAGE_PRESET_MAP.get(normalized) || null
}

export function buildLibTvImagePresetPrompt(args: {
  presetId: string
  userPrompt?: string
  referenceImageCount?: number
}) {
  const preset = getLibTvImagePresetById(args.presetId)
  if (!preset) {
    throw new Error("Unknown LibTV image preset")
  }

  const userPrompt = String(args.userPrompt || "").trim()
  const referenceImageCount = Math.max(0, Number(args.referenceImageCount || 0))
  const sections = [
    `${preset.label}`,
    ...preset.promptTemplate,
    referenceImageCount > 0
      ? `请严格参考我提供的 ${referenceImageCount} 张参考图，优先保持主体身份、服装、道具、镜头语义与场景一致性。`
      : (preset.allowTextOnly ? "如果没有参考图，请根据文字要求稳定完成该预设任务。" : "如果没有参考图，请提示我先补充参考图。"),
  ]

  if (userPrompt) {
    sections.push(`补充创作要求：${userPrompt}`)
  }

  if (preset.id === "portrait_texture_adjustment") {
    sections.push("输出要求：只返回最终成品画面；必须保持原人物、原构图和原场景关系，重点降低 AI 感、保留真实肤质和毛发细节，并统一人物与背景的色温、噪声、清晰度、边缘过渡和光影反射；不得出现水印、Logo、文字说明、变脸、换装、换背景或过度美颜。")
  } else if (preset.id === "blocking-storyboard") {
    sections.push("输出要求：只返回最终成品画面；必须是一张完整导演调度故事板蓝图，包含剧情分镜区、人物/物件索引、环境参考、机位调度图和底部镜头规划表；允许清晰中文短标签、编号、箭头和调度符号；不得出现水印、Logo、乱码或大段说明文字。")
  } else if (preset.id === "storyboard-sequence") {
    sections.push("输出要求：只返回最终成品画面；必须是一张完整专业故事板/视觉规划表，严格遵循 16:9 电影画幅、清晰网格分区和高对比中文排版；版式应呈现专业设计图式的信息层级，但具体标题、关键词、时长、场景和角色内容必须根据本次输入动态生成，不得照抄固定模板；完整包含 8 大核心模块，其中故事板主区必须是 8 个编号镜头格并清楚标注秒数，缺一不可；每个镜头说明控制在 1-2 行内；所有文字必须为清晰可读的简体中文；不得生成水印、Logo、乱码、伪文字或大段说明文字。")
  } else if (preset.id === "character-design-sheet") {
    sections.push("输出要求：只返回最终成品画面；允许清晰中文设定板标签、色号和短说明；不得出现水印、Logo、乱码、伪文字或大段说明文字。")
  } else if (preset.allowInImageText) {
    sections.push("输出要求：只返回最终成品画面；允许少量清晰中文分镜标注、箭头和调度符号；不得出现水印、Logo、乱码或大段说明文字。")
  } else {
    sections.push("输出要求：只返回最终成品画面；画面内部不得生成任何文字、标签、字幕、编号、水印、Logo 或说明性字符。")
  }
  return sections.join("\n")
}
